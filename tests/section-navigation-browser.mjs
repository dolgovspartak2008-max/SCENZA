import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir } from 'node:fs/promises';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.route('**/api/auth/session', route => route.fulfill({ json: { user: null } }));
await page.route('**/api/auth/config', route => route.fulfill({ json: { emailEnabled: true, telegramEnabled: false, emailCodeLength: 6 } }));
await page.route('**/scene.splinecode', route => route.abort());
const base = process.env.APP_URL || 'http://127.0.0.1:5173';
const current = () => page.locator('.scenza-section-nav a[aria-current="location"]').getAttribute('href');
const settled = () => page.waitForFunction(() => !document.querySelector('.scenza-section-nav[data-transitioning="true"]'));
const go = async id => {
  await page.locator(`.scenza-section-nav a[href="#${id}"]`).click();
  await settled();
  assert.equal(await current(), `#${id}`);
};

try {
  await page.goto(base);
  await page.locator('.scenza-hero').waitFor();
  await page.locator('.scenza-page-loader').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.scenza-section-nav a').count(), await page.locator('#scenza-main > section').count(), 'Navigation discovers every main section');
  assert.equal(await current(), '#hero');
  assert.ok(await page.locator('.scenza-section-nav').evaluate(el => el.getBoundingClientRect().left > innerWidth * .85), 'Desktop navigation is on the right');
  await page.locator('.scenza-section-nav a').first().hover();
  assert.ok(await page.locator('.scenza-section-name').first().evaluate(el => {
    const rect = el.getBoundingClientRect();
    const nav = document.querySelector('.scenza-section-nav').getBoundingClientRect();
    return rect.left >= 0 && rect.right < nav.left;
  }), 'Section labels open to the left and stay inside the viewport');
  await go('examples');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await go('hero');
  await page.mouse.move(1050, 600);
  for (let i = 0; i < 14; i++) await page.mouse.wheel(0, 120);
  await settled();
  assert.equal(await current(), '#examples', 'A wheel burst advances only one section');
  await page.waitForTimeout(240);
  await page.mouse.wheel(0, -120);
  await settled();
  assert.equal(await current(), '#hero', 'Upward wheel returns to previous section');
  await page.waitForTimeout(240);
  for (let i = 0; i < 18; i++) { await page.mouse.wheel(0, 4); await page.waitForTimeout(12); }
  await settled();
  assert.equal(await current(), '#examples', 'Small trackpad deltas accumulate into one transition');
  await page.locator('#examples').focus();
  await page.keyboard.press('ArrowDown');
  await settled();
  assert.equal(await current(), '#demo');
  const before = await page.evaluate(() => scrollY);
  await page.mouse.move(1400, 400);
  await page.waitForTimeout(240);
  await page.mouse.wheel(0, 70);
  await page.waitForTimeout(200);
  assert.equal(await current(), '#demo', 'Tall section remains active while reading');
  assert.ok(await page.evaluate(() => scrollY) > before, 'Tall content scrolls naturally');
  await page.locator('.pd-seek').focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await current(), '#demo', 'Slider keyboard input does not navigate');
  await go('pricing');
  await page.locator('.scenza-price-card').first().waitFor();
  await page.evaluate(() => window.scrollTo({ top: document.querySelector('#examples').offsetTop - 106, behavior: 'instant' }));
  await page.waitForFunction(() => document.querySelector('.scenza-section-nav a[aria-current="location"]')?.getAttribute('href') === '#examples');
  await go('faq');
  await page.mouse.wheel(0, 900);
  await page.waitForTimeout(250);
  assert.ok(await page.locator('.scenza-footer').evaluate(el => el.getBoundingClientRect().bottom <= innerHeight + 2), 'Footer remains reachable');
  await mkdir('tmp/ui-checks', { recursive: true });
  await go('hero');
  await page.screenshot({ path: 'tmp/ui-checks/section-nav-desktop.png' });
  const cta = page.locator('.scenza-hero-buttons .shiny-cta');
  assert.ok(await cta.evaluate(el => getComputedStyle(el, '::before').animationName.includes('scenza-shiny-border')));
  const angle = await cta.evaluate(el => getComputedStyle(el, '::before').getPropertyValue('--scenza-shiny-angle'));
  await page.waitForFunction(before => getComputedStyle(document.querySelector('.scenza-hero-buttons .shiny-cta'), '::before').getPropertyValue('--scenza-shiny-angle') !== before, angle);
  await cta.hover();
  await page.screenshot({ path: 'tmp/ui-checks/shiny-hover.png' });
  await page.locator('.scenza-section-nav a[href="#examples"]').click();
  await page.locator('.scenza-header-actions > .scenza-button-primary').click();
  await page.locator('dialog[open]').waitFor();
  const modalScroll = await page.evaluate(() => scrollY);
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.evaluate(() => scrollY), modalScroll, 'Dialog keyboard does not move page');
  await page.keyboard.press('Escape');
  await page.locator('dialog[open]').waitFor({ state: 'hidden' });
  await settled();
  await go('hero');
  assert.equal(new URL(page.url()).hash, '#hero', 'Navigation preserves shareable section anchors');
  await go('pricing');
  await go('faq');
  await page.goBack();
  await page.waitForFunction(() => location.hash === '#pricing');
  await page.locator('.scenza-desktop-nav a[href="#features"]').click();
  await settled();
  assert.equal(await page.evaluate(() => document.activeElement?.id), 'features', 'Nested anchor receives focus at its visible content');
  await go('hero');
  await page.locator('.scenza-header-actions .scenza-language button[lang="en"]').click();
  assert.match(await page.locator('.scenza-section-nav a').first().getAttribute('aria-label'), /Home/);
  await page.locator('.scenza-header-actions .scenza-language button[lang="ru"]').click();
  for (const width of [1024, 768, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.waitForTimeout(200);
    assert.equal(await page.locator('.scenza-section-nav').isVisible(), false);
    assert.ok(await page.locator('.scenza-section-indicator').isVisible());
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `${width}: no overflow`);
  }
  await page.mouse.wheel(0, 150);
  await page.waitForTimeout(250);
  assert.ok(await page.evaluate(() => scrollY > 50 && scrollY < 300), 'Mobile wheel is not intercepted');
  await page.screenshot({ path: 'tmp/ui-checks/section-nav-mobile.png' });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await go('hero');
  assert.equal(await cta.evaluate(el => getComputedStyle(el, '::before').animationName), 'none');
  await page.mouse.wheel(0, 150);
  await page.waitForTimeout(200);
  assert.ok(await page.evaluate(() => scrollY > 50 && scrollY < 300), 'Reduced motion keeps natural wheel scroll');
  await page.screenshot({ path: 'tmp/ui-checks/section-nav-reduced.png' });
  assert.deepEqual(errors, []);
  console.log('PASS section discovery, clicks, wheel directions/bursts, trackpad deltas, keyboard, tall sections, manual scroll, footer, responsive layout, reduced motion and page errors');
} finally {
  await browser.close();
}
